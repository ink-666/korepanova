// Класс Program содержит точку входа в программу
class Program
{
    // Main — главный метод, с которого начинается выполнение программы
    static void Main(string[] args)
    {
        // Выводим верхнюю границу заголовка
        Console.WriteLine("==========================================");

        // Выводим название лабораторной работы
        Console.WriteLine("ЛАБОРАТОРНАЯ РАБОТА: КЛАССЫ И НАСЛЕДОВАНИЕ");

        // Выводим тему работы
        Console.WriteLine("Тема: Транспортные средства");

        // Выводим нижнюю границу заголовка и пустую строку
        Console.WriteLine("==========================================\n");

        // ============= ЧАСТЬ 1: СОЗДАНИЕ ОБЪЕКТА Vehicle =============

        // Выводим заголовок первого шага
        Console.WriteLine("--- ШАГ 1: Создаём объект базового класса Vehicle ---");

        // Показываем, какой код создаёт объект Vehicle
        Console.WriteLine(">> В программе пишем: new Vehicle(\"Toyota\", \"Corolla\", 2022, 1800000)\n");

        // Создаём объект базового класса Vehicle
        Vehicle vehicle = new Vehicle("Toyota", "Corolla", 2022, 1800000);

        // Сообщаем, что объект создан
        Console.WriteLine(">> Объект создан! Теперь вызываем метод DisplayInfo():");

        // Вызываем метод вывода информации о Vehicle
        vehicle.DisplayInfo();

        // ============= ЧАСТЬ 2: СОЗДАНИЕ ОБЪЕКТА Car =============

        // Выводим заголовок второго шага
        Console.WriteLine("--- ШАГ 2: Создаём объект подкласса Car ---");

        // Показываем, какой код создаёт объект Car
        Console.WriteLine(">> В программе пишем: new Car(\"Toyota\", \"Camry\", 2022, 2900000, 4, \"седан\")");

        // Объясняем передачу данных между конструкторами
        Console.WriteLine(">> Данные передаются:\n");

        // Первый пункт объяснения
        Console.WriteLine("   1. Сначала вызывается конструктор Car");

        // Второй пункт объяснения
        Console.WriteLine("   2. Конструктор Car вызывает base(make, model, year, price)");

        // Третий пункт объяснения
        Console.WriteLine("   3. Выполняется конструктор Vehicle");

        // Четвёртый пункт объяснения
        Console.WriteLine("   4. Возвращаемся в конструктор Car для установки NumDoors и BodyStyle\n");

        // Создаём объект Car
        Car car = new Car("Toyota", "Camry", 2022, 2900000, 4, "седан");

        // Сообщаем, что объект Car создан
        Console.WriteLine(">> Объект Car создан! Вызываем метод DisplayInfo():");

        // Вызываем переопределённый метод DisplayInfo класса Car
        car.DisplayInfo();

        // ============= ЧАСТЬ 3: СОЗДАНИЕ ОБЪЕКТА Truck =============

        // Выводим заголовок третьего шага
        Console.WriteLine("--- ШАГ 3: Создаём объект подкласса Truck ---");

        // Показываем, какой код создаёт объект Truck
        Console.WriteLine(">> В программе пишем: new Truck(\"Ford\", \"F-MAX\", 2023, 6000000, \"6162 мм\", \"13 т\")\n");

        // Создаём объект Truck
        Truck truck = new Truck("Ford", "F-MAX", 2023, 6000000, "6162 мм", "13 т");

        // Сообщаем, что объект Truck создан
        Console.WriteLine(">> Объект Truck создан! Вызываем метод DisplayInfo():");

        // Вызываем переопределённый метод DisplayInfo класса Truck
        truck.DisplayInfo();

        // ============= ЧАСТЬ 4: ДЕМОНСТРАЦИЯ ПОЛИМОРФИЗМА =============

        // Выводим заголовок четвёртого шага
        Console.WriteLine("--- ШАГ 4: Демонстрация полиморфизма ---");

        // Объясняем, что в массиве базового типа будут разные объекты
        Console.WriteLine(">> Создаём массив объектов Vehicle, но храним в нём разные типы\n");

        // Создаём массив типа Vehicle на 3 элемента
        Vehicle[] vehicles = new Vehicle[3];

        // В первый элемент кладём объект Vehicle
        vehicles[0] = vehicle;

        // Во второй элемент кладём объект Car, он автоматически воспринимается как Vehicle
        vehicles[1] = car;

        // В третий элемент кладём объект Truck, он тоже автоматически воспринимается как Vehicle
        vehicles[2] = truck;

        // Объясняем, что дальше будет вызов DisplayInfo для каждого элемента
        Console.WriteLine(">> Проходим по массиву и вызываем DisplayInfo() для каждого:");

        // Объясняем суть полиморфизма
        Console.WriteLine(">> Несмотря на то, что все элементы типа Vehicle, вызываются");

        // Продолжаем объяснение
        Console.WriteLine(">> методы соответствующих классов (полиморфизм!):\n");

        // Цикл проходит по всем элементам массива vehicles
        for (int i = 0; i < vehicles.Length; i++)
        {
            // Выводим номер элемента
            Console.WriteLine($"Элемент {i + 1}:");

            // Вызывается версия DisplayInfo реального класса объекта: Vehicle, Car или Truck
            vehicles[i].DisplayInfo();
        }

        // ============= ИТОГ =============

        // Выводим разделитель
        Console.WriteLine("==========================================");

        // Выводим заголовок итогов
        Console.WriteLine("ИТОГ РАБОТЫ:");

        // Выводим разделитель
        Console.WriteLine("==========================================");

        // Итог: создан базовый класс
        Console.WriteLine("✓ Создан базовый класс Vehicle");

        // Итог: созданы подклассы
        Console.WriteLine("✓ Созданы подклассы Car и Truck");

        // Итог: показано наследование
        Console.WriteLine("✓ Продемонстрировано наследование");

        // Итог: показана передача данных через конструкторы
        Console.WriteLine("✓ Показана передача данных через конструкторы");

        // Итог: показан полиморфизм методов
        Console.WriteLine("✓ Показан полиморфизм методов");

        // Финальный разделитель
        Console.WriteLine("==========================================");
    }
}