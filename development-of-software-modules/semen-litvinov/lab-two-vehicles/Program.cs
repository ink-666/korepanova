using System; // Подключает базовые классы C#, например Console

// ==========================================================
// БАЗОВЫЙ КЛАСС Vehicle (Транспортное средство)
// ==========================================================

// Класс Vehicle описывает общее транспортное средство
class Vehicle
{
    // АТРИБУТЫ (свойства класса)

    // Марка транспортного средства
    public string Make { get; set; }

    // Модель транспортного средства
    public string Model { get; set; }

    // Год выпуска
    public int Year { get; set; }

    // Стоимость
    public decimal Price { get; set; }

    // КОНСТРУКТОР - вызывается при создании объекта Vehicle
    // В него передаются данные из программы
    public Vehicle(string make, string model, int year, decimal price)
    {
        // Показываем, что начал работу конструктор Vehicle
        Console.WriteLine(">>> ВЫЗВАН КОНСТРУКТОР Vehicle");

        // Выводим параметры, которые пришли в конструктор
        Console.WriteLine($"    Получены параметры: make={make}, model={model}, year={year}, price={price}");

        // Присваиваем полученную марку свойству Make
        Make = make;

        // Присваиваем полученную модель свойству Model
        Model = model;

        // Присваиваем полученный год выпуска свойству Year
        Year = year;

        // Присваиваем полученную цену свойству Price
        Price = price;

        // Показываем, какие значения теперь хранятся в свойствах объекта
        Console.WriteLine($"    Атрибутам присвоены значения: {Make}, {Model}, {Year}, {Price} руб.");

        // Сообщаем, что конструктор завершил работу
        Console.WriteLine("<<< КОНСТРУКТОР Vehicle ЗАВЕРШЕН\n");
    }

    // МЕТОД для вывода информации о транспортном средстве
    // virtual означает, что метод можно переопределить в дочерних классах
    public virtual void DisplayInfo()
    {
        // Выводим заголовок блока информации
        Console.WriteLine("--- Информация о транспортном средстве ---");

        // Выводим марку
        Console.WriteLine($"Марка: {Make}");

        // Выводим модель
        Console.WriteLine($"Модель: {Model}");

        // Выводим год выпуска
        Console.WriteLine($"Год выпуска: {Year}");

        // Выводим стоимость
        Console.WriteLine($"Стоимость: {Price} руб.");

        // Выводим нижнюю границу блока
        Console.WriteLine("------------------------------------------\n");
    }
}

// ==========================================================
// ПОДКЛАСС Car (Легковой автомобиль) - наследует от Vehicle
// ==========================================================

// Класс Car наследуется от Vehicle и получает его свойства Make, Model, Year и Price
class Car : Vehicle
{
    // ДОПОЛНИТЕЛЬНЫЕ АТРИБУТЫ, которые есть именно у легкового автомобиля

    // Количество дверей
    public int NumDoors { get; set; }

    // Тип кузова
    public string BodyStyle { get; set; }

    // КОНСТРУКТОР Car
    // Он принимает общие данные для Vehicle и дополнительные данные для Car
    public Car(string make, string model, int year, decimal price, int numDoors, string bodyStyle)
        : base(make, model, year, price) // Передаём make, model, year и price в конструктор базового класса Vehicle
    {
        // Показываем, что начал работу конструктор Car
        Console.WriteLine(">>> ВЫЗВАН КОНСТРУКТОР Car");

        // Выводим дополнительные параметры, которые относятся только к Car
        Console.WriteLine($"    Получены дополнительные параметры: дверей={numDoors}, кузов={bodyStyle}");

        // Сохраняем количество дверей в свойство NumDoors
        NumDoors = numDoors;

        // Сохраняем тип кузова в свойство BodyStyle
        BodyStyle = bodyStyle;

        // Показываем, какие дополнительные свойства установлены
        Console.WriteLine($"    Дополнительные атрибуты установлены: {NumDoors} двери, тип кузова {BodyStyle}");

        // Сообщаем, что конструктор Car завершил работу
        Console.WriteLine("<<< КОНСТРУКТОР Car ЗАВЕРШЕН\n");
    }

    // ПЕРЕОПРЕДЕЛЁННЫЙ МЕТОД DisplayInfo
    // override означает, что этот метод заменяет версию из Vehicle
    public override void DisplayInfo()
    {
        // Выводим заголовок блока легкового автомобиля
        Console.WriteLine("========== ЛЕГКОВОЙ АВТОМОБИЛЬ ==========");

        // Выводим марку, унаследованную от Vehicle
        Console.WriteLine($"Марка: {Make}");

        // Выводим модель, унаследованную от Vehicle
        Console.WriteLine($"Модель: {Model}");

        // Выводим год выпуска, унаследованный от Vehicle
        Console.WriteLine($"Год выпуска: {Year}");

        // Выводим стоимость, унаследованную от Vehicle
        Console.WriteLine($"Стоимость: {Price} руб.");

        // Выводим количество дверей, свойственное Car
        Console.WriteLine($"Количество дверей: {NumDoors}");

        // Выводим тип кузова, свойственный Car
        Console.WriteLine($"Тип кузова: {BodyStyle}");

        // Выводим нижнюю границу блока
        Console.WriteLine("==========================================\n");
    }
}

// ==========================================================
// ПОДКЛАСС Truck (Грузовик) - наследует от Vehicle
// ==========================================================

// Класс Truck наследуется от Vehicle и добавляет свойства грузовика
class Truck : Vehicle
{
    // ДОПОЛНИТЕЛЬНЫЕ АТРИБУТЫ, которые есть именно у грузовика

    // Длина кузова
    public string BedLength { get; set; }

    // Тяговая мощность
    public string TowingCapacity { get; set; }

    // КОНСТРУКТОР Truck
    // Он принимает общие данные для Vehicle и дополнительные данные для Truck
    public Truck(string make, string model, int year, decimal price, string bedLength, string towingCapacity)
        : base(make, model, year, price) // Передаём make, model, year и price в конструктор Vehicle
    {
        // Показываем, что начал работу конструктор Truck
        Console.WriteLine(">>> ВЫЗВАН КОНСТРУКТОР Truck");

        // Выводим параметры, которые относятся только к Truck
        Console.WriteLine($"    Получены дополнительные параметры: длина кузова={bedLength}, тяга={towingCapacity}");

        // Сохраняем длину кузова в свойство BedLength
        BedLength = bedLength;

        // Сохраняем тяговую мощность в свойство TowingCapacity
        TowingCapacity = towingCapacity;

        // Показываем, какие дополнительные свойства установлены
        Console.WriteLine($"    Дополнительные атрибуты установлены: кузов {BedLength}, тяга {TowingCapacity}");

        // Сообщаем, что конструктор Truck завершил работу
        Console.WriteLine("<<< КОНСТРУКТОР Truck ЗАВЕРШЕН\n");
    }

    // ПЕРЕОПРЕДЕЛЁННЫЙ МЕТОД DisplayInfo
    // Для Truck выводится информация именно о грузовике
    public override void DisplayInfo()
    {
        // Выводим заголовок блока грузовика
        Console.WriteLine("============== ГРУЗОВИК ==============");

        // Выводим марку, унаследованную от Vehicle
        Console.WriteLine($"Марка: {Make}");

        // Выводим модель, унаследованную от Vehicle
        Console.WriteLine($"Модель: {Model}");

        // Выводим год выпуска, унаследованный от Vehicle
        Console.WriteLine($"Год выпуска: {Year}");

        // Выводим стоимость, унаследованную от Vehicle
        Console.WriteLine($"Стоимость: {Price} руб.");

        // Выводим длину кузова грузовика
        Console.WriteLine($"Длина кузова: {BedLength}");

        // Выводим тяговую мощность грузовика
        Console.WriteLine($"Тяговая мощность: {TowingCapacity}");

        // Выводим нижнюю границу блока
        Console.WriteLine("=======================================\n");
    }
}

